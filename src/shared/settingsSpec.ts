// STEP 13: FOMO fee model on Solana (fees.py)
export function calculateFomoFee(usd: number): number {
  if (usd <= 0) return 0;
  if (usd < 5) return 0.1;
  if (usd <= 47.5) return Number((usd * 0.02).toFixed(2));
  if (usd <= 190) return 0.95;
  return Number((usd * 0.0045).toFixed(2));
}
